//! The TypeScript types in `ui/src/lib/types/` are generated from the Rust
//! types in `src/types.rs` (ts-rs). This test fails when they are stale;
//! `UPDATE_TS_TYPES=1 cargo test -p wrapped-dashboard --test ts_types`
//! rewrites them.

use std::collections::BTreeSet;
use std::path::PathBuf;

#[test]
fn ts_types_are_up_to_date() {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("ui/src/lib/types");
    let update = std::env::var_os("UPDATE_TS_TYPES").is_some_and(|v| !v.is_empty() && v != "0");
    let files = wrapped_dashboard::types::typescript_files();
    let mut index = String::from("// Generated by dashboard/tests/ts_types.rs. Do not edit.\n");
    for (name, _) in &files {
        let stem = name.trim_end_matches(".ts");
        index.push_str(&format!("export type {{ {stem} }} from \"./{stem}\";\n"));
    }
    let mut expected: Vec<(String, String)> = files;
    expected.push(("index.ts".into(), index));

    if update {
        std::fs::create_dir_all(&dir).unwrap();
        for entry in std::fs::read_dir(&dir).unwrap() {
            let p = entry.unwrap().path();
            if p.extension().is_some_and(|e| e == "ts") {
                std::fs::remove_file(p).unwrap();
            }
        }
        for (name, src) in &expected {
            std::fs::write(dir.join(name), src).unwrap();
        }
        return;
    }

    let mut stale = Vec::new();
    for (name, src) in &expected {
        // Compare without line-ending differences (a Windows checkout).
        let on_disk = std::fs::read_to_string(dir.join(name))
            .ok()
            .map(|s| s.replace("\r\n", "\n"));
        if on_disk.as_deref() != Some(src.as_str()) {
            stale.push(name.clone());
        }
    }
    let wanted: BTreeSet<&str> = expected.iter().map(|(n, _)| n.as_str()).collect();
    let extra: Vec<String> = std::fs::read_dir(&dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok()?.file_name().into_string().ok())
                .filter(|n| n.ends_with(".ts") && !wanted.contains(n.as_str()))
                .collect()
        })
        .unwrap_or_default();
    assert!(
        stale.is_empty() && extra.is_empty(),
        "TypeScript types are stale (changed or missing: {stale:?}; no longer generated: {extra:?}).\n\
         Regenerate: UPDATE_TS_TYPES=1 cargo test -p wrapped-dashboard --test ts_types"
    );
}
